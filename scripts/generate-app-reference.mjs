import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const srcDir = path.join(root, 'src')
const outputPath = path.join(srcDir, 'data', 'sourceCodeIndex.generated.ts')

const IGNORED_DIRS = new Set(['node_modules', 'dist', 'android'])
const INCLUDED_EXTENSIONS = new Set(['.ts', '.tsx', '.css', '.json'])
const EXCLUDED_FILES = new Set([
	path.join(srcDir, 'data', 'sourceCodeIndex.generated.ts'),
])

async function walk(directory) {
	const entries = await readdir(directory, { withFileTypes: true })
	const files = []

	for (const entry of entries) {
		const fullPath = path.join(directory, entry.name)
		if (entry.isDirectory()) {
			if (IGNORED_DIRS.has(entry.name)) {
				continue
			}
			files.push(...(await walk(fullPath)))
			continue
		}

		const extension = path.extname(entry.name)
		if (!INCLUDED_EXTENSIONS.has(extension)) {
			continue
		}

		if (EXCLUDED_FILES.has(fullPath)) {
			continue
		}

		files.push(fullPath)
	}

	return files.sort()
}

function escapeForTemplateLiteral(value) {
	return value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

async function main() {
	const files = await walk(srcDir)
	const entries = []

	for (const filePath of files) {
		const relativePath = path.relative(root, filePath).replace(/\\/g, '/')
		const content = await readFile(filePath, 'utf8')
		entries.push({ path: relativePath, content })
	}

	const body = entries
		.map(
			(entry) =>
				`\t'${entry.path.replace(/'/g, "\\'")}': \`${escapeForTemplateLiteral(entry.content)}\`,`,
		)
		.join('\n')

	const output = `// Generated by scripts/generate-app-reference.mjs — do not edit manually.
export const SOURCE_CODE_GENERATED_AT = '${new Date().toISOString()}'

export const SOURCE_CODE_PATHS = [
${entries.map((entry) => `\t'${entry.path.replace(/'/g, "\\'")}',`).join('\n')}
] as const

export const SOURCE_CODE_INDEX: Record<string, string> = {
${body}
}
`

	await writeFile(outputPath, output, 'utf8')
	console.log(`Wrote ${entries.length} source files to ${path.relative(root, outputPath)}`)
}

await main()
